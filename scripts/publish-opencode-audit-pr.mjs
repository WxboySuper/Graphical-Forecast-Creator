import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const token = process.env.GH_TOKEN;
const repository = process.env.GITHUB_REPOSITORY;
const issueNumber = Number(process.env.AUDIT_ISSUE_NUMBER);
const branch = process.env.AUDIT_BRANCH;
const base = process.env.DEFAULT_BRANCH;
const paths = JSON.parse(process.env.CHANGED_PATHS ?? '[]');
const summary = String(process.env.WORK_SUMMARY ?? '').trim();
const validationSummary = String(process.env.VALIDATION_SUMMARY ?? '').trim();
const statePath = process.env.WORKER_STATE_PATH;

if (!token || !repository || !Number.isInteger(issueNumber) || !branch || !base || !paths.length || !summary || !validationSummary || !statePath) {
  throw new Error('Audit PR publisher configuration is incomplete.');
}
if (!/^opencode\/audit-\d+-\d+-\d+$/.test(branch)) throw new Error('Refusing an unexpected OpenCode branch name.');

const state = JSON.parse(readFileSync(statePath, 'utf8'));
const runGit = (args, options = {}) => {
  const result = spawnSync('git', args, { encoding: 'utf8', ...options });
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? '');
    process.stderr.write(result.stderr ?? '');
    throw new Error(`Git command failed: git ${args[0]}`);
  }
  return result.stdout.trim();
};

runGit(['config', 'user.name', 'github-actions[bot]']);
runGit(['config', 'user.email', '41898282+github-actions[bot]@users.noreply.github.com']);
runGit(['add', '--', ...paths]);
runGit(['diff', '--cached', '--check']);
runGit(['commit', '-m', `Fix audit issue #${issueNumber}`]);
const headSha = runGit(['rev-parse', 'HEAD']);
const authorization = `AUTHORIZATION: basic ${Buffer.from(`x-access-token:${token}`).toString('base64')}`;
runGit(['-c', `http.https://github.com/.extraheader=${authorization}`, 'push', 'origin', `HEAD:refs/heads/${branch}`]);

const [owner, repo] = repository.split('/');
const apiBase = `https://api.github.com/repos/${owner}/${repo}`;
const headers = {
  Accept: 'application/vnd.github+json',
  Authorization: `Bearer ${token}`,
  'X-GitHub-Api-Version': '2022-11-28',
  'Content-Type': 'application/json',
};
const issueTitle = String(state.issueTitle ?? `Audit issue #${issueNumber}`).replace(/^\[OpenCode [^\]]+\]\s*/, '').slice(0, 140);
const response = await fetch(`${apiBase}/pulls`, {
  method: 'POST',
  headers,
  body: JSON.stringify({
    title: `[OpenCode fix] ${issueTitle}`,
    head: branch,
    base,
    body: `Fixes #${issueNumber}\n\n${summary}\n\nThe implementation worker rechecked the audit finding and limited changes to \`${state.scope}\`. Workflow validation passed: ${validationSummary}. Please review the change and CI before merging. This PR must be merged by a human.\n\nGenerated by the bounded GFC maintenance worker.`,
    maintainer_can_modify: false,
  }),
});
const pull = await response.json();
if (!response.ok) throw new Error(`GitHub could not open the audit PR (${response.status}): ${String(pull.message ?? '').slice(0, 300)}`);

const ensureLabel = async (name, color, description) => {
  const label = await fetch(`${apiBase}/labels/${encodeURIComponent(name)}`, { headers });
  if (label.ok) return;
  const created = await fetch(`${apiBase}/labels`, {
    method: 'POST', headers, body: JSON.stringify({ name, color, description }),
  });
  if (!created.ok && created.status !== 422) throw new Error(`Could not create issue label ${name}.`);
};
await ensureLabel('opencode-audit-pr', '0e8a16', 'A bounded OpenCode worker opened a pull request for this audit issue.');

const addLabel = await fetch(`${apiBase}/issues/${issueNumber}/labels`, {
  method: 'POST', headers, body: JSON.stringify({ labels: ['opencode-audit-pr'] }),
});
if (!addLabel.ok) throw new Error('Could not mark the audit issue as having an implementation PR.');
for (const label of ['opencode-audit-eligible', 'opencode-audit-claimed']) {
  const removed = await fetch(`${apiBase}/issues/${issueNumber}/labels/${encodeURIComponent(label)}`, { method: 'DELETE', headers });
  if (!removed.ok && removed.status !== 404) throw new Error(`Could not remove the ${label} issue label.`);
}

const workerState = {
  status: 'pr-open',
  issue: issueNumber,
  branch,
  headSha,
  pullRequest: pull.number,
  pullRequestUrl: pull.html_url,
  at: new Date().toISOString(),
};
const commentResponse = await fetch(`${apiBase}/issues/comments/${state.stateCommentId}`, {
  method: 'PATCH',
  headers,
  body: JSON.stringify({ body: `<!-- gfc-opencode-audit-worker:v1 -->\n${JSON.stringify(workerState)}` }),
});
if (!commentResponse.ok) throw new Error('Could not save the audit worker PR state.');
state.status = 'pr-open';
state.pullRequest = pull.number;
state.pullRequestUrl = pull.html_url;
state.headSha = headSha;
writeFileSync(statePath, JSON.stringify(state), 'utf8');

const dispatch = await fetch(`${apiBase}/actions/workflows/opencode-first-look.yml/dispatches`, {
  method: 'POST',
  headers,
  body: JSON.stringify({
    ref: base,
    inputs: { pull_number: String(pull.number), expected_sha: headSha },
  }),
});
if (!dispatch.ok) {
  process.stderr.write(`PR ${pull.html_url} opened, but first-look dispatch failed with ${dispatch.status}.\n`);
  process.exitCode = 1;
} else {
  process.stdout.write(`Opened ${pull.html_url} and dispatched first-look review.\n`);
}
